def _hook_cmd(agent: str) -> str:
    if agent == "claude":
        return f'python3 "$CLAUDE_PROJECT_DIR/{STOP_GUARD_REL}"'
    return f'python3 "$(git rev-parse --show-toplevel)/{STOP_GUARD_REL}" --agent {agent}'


def _merge_stop_hook(data: dict, cmd: str) -> dict:
    hooks = data.setdefault("hooks", {})
    stop = hooks.setdefault("Stop", [])
    for group in stop:
        for h in group.get("hooks", []):
            if STOP_GUARD_REL in h.get("command", ""):
                h["command"] = cmd
                h["type"] = "command"
                return data
    stop.append({"hooks": [{"type": "command", "command": cmd}]})
    return data


def _json_dump(data: dict) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def sync_hooks(plan: Plan, agent: str):
    root = plan.root
    if not (root / STOP_GUARD_REL).is_file():
        return
    path = {"claude": root / ".claude" / "settings.json",
            "codex": root / ".codex" / "hooks.json",
            "dsh": root / ".dsh" / "hooks.json"}[agent]
    try:
        data = json.loads(_read(path) or "{}")
    except json.JSONDecodeError:
        raise SystemExit(f"[agent_sync] {path} 不是合法 JSON，拒绝覆盖，请先修复")
    plan.write_text(path, _json_dump(_merge_stop_hook(data, _hook_cmd(agent))))
    if agent == "codex":
        cfg = root / ".codex" / "config.toml"
        text = _read(cfg)
        merged = _merge_codex_hook_flag(text)
        if merged != text:
            plan.write_text(cfg, merged)


# ── 主流程 ────────────────────────────────────────────────────────────────────
def _name_conflicts(root: Path, plugin_skills: dict) -> list:
    skills = set(_base_skill_dirs(root)) | set(plugin_skills)
    commands = {path.stem for path in _command_files(root)}
    return sorted(skills & commands)


def _json_object(path: Path, label: str) -> dict:
    try:
        value = json.loads(_read(path) or "{}")
    except json.JSONDecodeError as exc:
        raise SystemExit(f"[agent_sync] {label} JSON 非法：{exc}")
    if not isinstance(value, dict):
        raise SystemExit(f"[agent_sync] {label} 类型错误：顶层必须是对象")
    return value


def _validate_hook_structure(data: dict, path: Path):
    hooks = data.get("hooks", {})
    if not isinstance(hooks, dict):
        raise SystemExit(f"[agent_sync] hooks 结构错误：{path} 的 hooks 必须是对象")
    stop = hooks.get("Stop", [])
    if not isinstance(stop, list):
        raise SystemExit(f"[agent_sync] hooks 结构错误：{path} 的 Stop 必须是数组")
    for index, group in enumerate(stop):
        if not isinstance(group, dict):
            raise SystemExit(f"[agent_sync] hooks 结构错误：{path} Stop[{index}] 必须是对象")
        entries = group.get("hooks", [])
        if not isinstance(entries, list):
            raise SystemExit(f"[agent_sync] hooks 结构错误：{path} Stop[{index}].hooks 必须是数组")
        for hook_index, hook in enumerate(entries):
            if not isinstance(hook, dict):
                raise SystemExit(
                    f"[agent_sync] hooks 结构错误：{path} Stop[{index}].hooks[{hook_index}] 必须是对象")
            if "command" in hook and not isinstance(hook["command"], str):
                raise SystemExit(f"[agent_sync] hooks 结构错误：{path} command 必须是字符串")
            if "type" in hook and not isinstance(hook["type"], str):
                raise SystemExit(f"[agent_sync] hooks 结构错误：{path} type 必须是字符串")


def _validate_codex_features(root: Path):
    path = root / ".codex/config.toml"
    text = _read(path)
    feature_headers = list(re.finditer(r"(?m)^[ \t]*\[features\][ \t]*$", text))
    assignments = list(re.finditer(r"(?m)^[ \t]*codex_hooks[ \t]*=.*$", text))
    hook_keys = list(CODEX_HOOK_LINE_RE.finditer(text))
    if len(feature_headers) > 1:
        raise SystemExit(f"[agent_sync] Codex features 结构错误：{path} 含重复 [features] section")
    if len(assignments) > 1:
        raise SystemExit(f"[agent_sync] Codex features 结构错误：{path} 含重复 codex_hooks 键")
    if assignments and not hook_keys:
        raise SystemExit(f"[agent_sync] Codex features 结构错误：codex_hooks 必须是 true/false")
    if hook_keys:
        if not feature_headers:
            raise SystemExit(f"[agent_sync] Codex features 结构错误：codex_hooks 不在 [features] section")
        start = feature_headers[0].end()
        next_header = re.search(r"(?m)^[ \t]*\[", text[start:])
        end = start + next_header.start() if next_header else len(text)
        if not (start <= hook_keys[0].start() < end):
            raise SystemExit(f"[agent_sync] Codex features 结构错误：codex_hooks 不在 [features] section")


def _merge_codex_hook_flag(text: str) -> str:
    if CODEX_HOOK_LINE_RE.search(text):
        def replace(match):
            return (f"{match.group('indent')}codex_hooks{match.group('before')}="
                    f"{match.group('after')}true{match.group('comment')}")
        return CODEX_HOOK_LINE_RE.sub(replace, text, count=1)
    if re.search(r"(?m)^[ \t]*\[features\][ \t]*$", text):
        return re.sub(r"(?m)^([ \t]*\[features\][ \t]*)$", r"\1\ncodex_hooks = true", text, count=1)
    return (text.rstrip() + "\n\n" if text.strip() else "") + "[features]\ncodex_hooks = true\n"


def _validate_hooks(root: Path, agents: list):
    if not (root / STOP_GUARD_REL).is_file():
        return
    paths = {"claude": root / ".claude/settings.json",
             "codex": root / ".codex/hooks.json",
             "dsh": root / ".dsh/hooks.json"}
    for agent in agents:
        path = paths[agent]
        data = _json_object(path, f"{agent} hooks {path}") if path.exists() else {}
        _validate_hook_structure(data, path)
        _merge_stop_hook(json.loads(json.dumps(data)), _hook_cmd(agent))
    if "codex" in agents:
        _validate_codex_features(root)


def _validate_claude_plugins(root: Path, plugins: list):
    marker_path = root / CLAUDE_PLUGIN_MANAGED
    settings_path = root / ".claude/settings.json"
    if not plugins and not marker_path.is_file():
        return
    settings = _json_object(settings_path, "Claude settings")
    marker = _json_object(marker_path, "Claude plugin marker") if marker_path.is_file() else {}
    for field in ("marketplaces", "enabledPlugins"):
        values = marker.get(field, [])
        if not isinstance(values, list) or any(not isinstance(item, str) for item in values):
            raise SystemExit(f"[agent_sync] Claude plugin marker 字段类型错误：{field}")
    markets = settings.get("extraKnownMarketplaces", {})
    enabled = settings.get("enabledPlugins", {})
    if not isinstance(markets, dict):
        raise SystemExit("[agent_sync] Claude settings 字段类型错误：extraKnownMarketplaces 必须是对象")
    if not isinstance(enabled, dict):
        raise SystemExit("[agent_sync] Claude settings 字段类型错误：enabledPlugins 必须是对象")
    markets = dict(markets)
    enabled = dict(enabled)
    for key in marker.get("marketplaces", []):
        markets.pop(key, None)
    for key in marker.get("enabledPlugins", []):
        enabled.pop(key, None)

    for plugin in plugins:
        marketplace_path = plugin / ".claude-plugin/marketplace.json"
        marketplace = _json_object(marketplace_path, f"Claude marketplace {marketplace_path}") \
            if marketplace_path.is_file() else {}
        name = marketplace.get("name") or f"{plugin.name}-marketplace"
        entries = marketplace.get("plugins", [{"name": plugin.name}])
        if not isinstance(name, str) or not isinstance(entries, list) \
                or any(not isinstance(entry, dict) for entry in entries):
            raise SystemExit(f"[agent_sync] Claude marketplace 字段类型错误：{marketplace_path}")
        desired = {"source": {"source": "directory", "path": f"./{CLAUDE_PLUGINS}/{plugin.name}"}}
        if name in markets and markets[name] != desired:
            raise SystemExit(f"[agent_sync] Claude marketplace 用户配置冲突：{name}")
        for entry in entries:
            plugin_name = entry.get("name", plugin.name)
            if not isinstance(plugin_name, str):
                raise SystemExit(f"[agent_sync] Claude marketplace 字段类型错误：{marketplace_path}")
            key = f"{plugin_name}@{name}"
            if key in enabled and enabled[key] is not True:
                raise SystemExit(f"[agent_sync] Claude enabledPlugins 用户配置冲突：{key}")


def _validate_real_namespace(root: Path, rel: str, label: str):
    current = root
    for part in Path(rel).parts:
        current = current / part
        if current.is_symlink():
            raise SystemExit(f"[agent_sync] {label} 必须位于真实目录，拒绝 symlink：{current}")
        if current.exists() and not current.is_dir():
            raise SystemExit(f"[agent_sync] {label} 必须位于真实目录，发现非目录：{current}")


def _validate_adapter_namespaces(root: Path, plugins: list):
    namespaces = {
        ".claude", CLAUDE_SKILLS, CLAUDE_COMMANDS, CLAUDE_PLUGINS,
        ".codex", CODEX_PLUGIN_SKILLS, CODEX_COMMAND_SKILLS,
        ".dsh", DSH_COMMANDS, ".dsh/skills",
        ".agents", SHARED_SKILLS, LEGACY_CODEX_PLUGINS,
    }
    namespaces.update(f"{CODEX_PLUGIN_SKILLS}/{plugin.name}" for plugin in plugins
                      if (plugin / "skills").is_dir())
    for rel in sorted(namespaces, key=lambda item: (len(Path(item).parts), item)):
        _validate_real_namespace(root, rel, f"Agent 适配 namespace {rel}")


def _validate_targets(root: Path, agents: list, plugins: list, plugin_skills: dict):
    if "claude" in agents:
        for name in _base_skill_dirs(root):
            _require_generated_or_absent(root / CLAUDE_SKILLS / name, "Claude SKILL 入口")
        destination = root / CLAUDE_COMMANDS
        previous = _generated_names(destination / GENERATED_FILE)
        for command in _command_files(root):
            target = destination / command.name
            if ((target.exists() or target.is_symlink()) and command.name not in previous
                    and not _is_generated(target)):
                raise SystemExit(f"[agent_sync] Claude 命令目标已存在用户内容，拒绝覆盖：{target}")
        for plugin in plugins:
            _require_generated_or_absent(root / CLAUDE_PLUGINS / plugin.name,
                                         "Claude 插件目录")
    if "codex" in agents:
        for command in _command_files(root):
            _require_generated_or_absent(root / CODEX_COMMAND_SKILLS / command.stem,
                                         "Codex 命令 SKILL")
        for plugin in plugins:
            if (plugin / "skills").is_dir():
                _require_generated_or_absent(root / CODEX_PLUGIN_SKILLS / plugin.name,
                                             "Codex 插件 SKILL 目录")
    if "dsh" in agents:
        destination = root / DSH_COMMANDS
        previous = _generated_names(destination / GENERATED_FILE)
        for command in _command_files(root):
            target = destination / command.name
            if ((target.exists() or target.is_symlink()) and command.name not in previous
                    and not _is_generated(target)):
                raise SystemExit(f"[agent_sync] 原生命令目标已存在用户内容，拒绝覆盖：{target}")
    if "codex" in agents or "dsh" in agents:
        desired = _base_skill_dirs(root)
        if "dsh" in agents:
            desired = {**desired, **plugin_skills}
        for name in desired:
            _require_generated_or_absent(root / SHARED_SKILLS / name, "SKILL 入口")


def run(root: Path, agents: list, mode: str, apply: bool) -> dict:
    plugins = _plugin_dirs(root)
    plugin_skills = _plugin_skill_dirs(plugins) if ({"codex", "dsh"} & set(agents)) else {}
    public_skills = set(_base_skill_dirs(root))
    skill_clash = sorted(public_skills & set(plugin_skills))
    if skill_clash:
        raise SystemExit(f"[agent_sync] 插件 SKILL 与公共 SKILL 同名冲突：{', '.join(skill_clash)}")
    clash = _name_conflicts(root, plugin_skills)
    if clash:
        raise SystemExit(f"[agent_sync] 命令与 SKILL 同名冲突：{', '.join(clash)}，请改名其一")
    all_servers = _plugin_servers(plugins)
    _validate_adapter_namespaces(root, plugins)
    _validate_targets(root, agents, plugins, plugin_skills)
    _validate_hooks(root, agents)
    _validate_claude_plugins(root, plugins if "claude" in agents else [])
    if "codex" in agents:
        _validate_codex_mcp(root, all_servers)
    if "dsh" in agents:
        _validate_dsh_mcp(root, all_servers)

    plan = Plan(root, apply, mode)
    sync_memory(plan, agents)
    for agent in agents:
        sync_hooks(plan, agent)
    legacy_plugins = cleanup_legacy_codex_plugins(plan)
    generated = []

    if "claude" in agents:
        generated += sync_skill_dir(plan, CLAUDE_SKILLS)
        generated += sync_file_commands(plan, CLAUDE_COMMANDS)
        generated += sync_claude_plugins(plan, plugins)
    else:
        _prune(plan, root / CLAUDE_SKILLS, set())
        sync_file_commands(plan, CLAUDE_COMMANDS, enabled=False)
        sync_claude_plugins(plan, [])

    if "codex" in agents or "dsh" in agents:
        extras = plugin_skills if "dsh" in agents else {}
        generated += sync_skill_dir(plan, SHARED_SKILLS, extras)
    else:
        _prune(plan, root / SHARED_SKILLS, set())

    if "codex" in agents:
        generated += sync_codex_commands(plan)
        generated += sync_codex_plugin_skills(plan, plugins)
        sync_codex_mcp(plan, all_servers, legacy_plugins)
    else:
        _prune(plan, root / CODEX_COMMAND_SKILLS, set())
        sync_codex_plugin_skills(plan, [])
        sync_codex_mcp(plan, {}, legacy_plugins)

    if "dsh" in agents:
        generated += sync_file_commands(plan, DSH_COMMANDS)
        generated += sync_dsh_mcp(plan, all_servers)
    else:
        sync_file_commands(plan, DSH_COMMANDS, enabled=False)
        generated += sync_dsh_mcp(plan, {})

    _prune(plan, root / LEGACY_CODEX_COMMAND_SKILLS, set())
    _prune(plan, root / ".dsh/skills", set())
    sync_gitignore(plan, generated)
    return {"agents": agents, "mode": mode, "applied": apply,
            "drift": bool(plan.actions), "actions": plan.actions}


