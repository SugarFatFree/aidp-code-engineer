# ── 通用小工具 ────────────────────────────────────────────────────────────────
def _read(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return ""


def _frontmatter(text: str) -> dict:
    """只解析 `key: value` 单行形式，够读 description / argument-hint。"""
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n", text, re.S)
    out = {}
    if not m:
        return out
    for line in m.group(1).splitlines():
        kv = re.match(r"^([A-Za-z_-]+)\s*:\s*(.*)$", line)
        if kv:
            out[kv.group(1)] = kv.group(2).strip().strip('"').strip("'")
    return out


def _title_description(text: str) -> str:
    """命令文件无 frontmatter 时，取首个 H1「# /name — 说明」里破折号后的说明（去掉标题装饰符 ★）。"""
    m = re.search(r"^#\s+/?[\w-]+\s*[—-]+\s*(.+?)\s*$", text, re.M)
    if not m:
        return ""
    desc = re.sub(r"[（(]\s*★\s*[)）]|★", "", m.group(1)).strip()
    return f"AIDP 命令：{desc}"


def _is_shell(text: str) -> bool:
    body = [l for l in text.splitlines() if l.strip() and not l.strip().startswith("<!--")]
    return len(body) == 1 and body[0].strip() == "@AGENTS.md"


class Plan:
    """收集动作；apply=False 时只记录不落盘。"""

    def __init__(self, root: Path, apply: bool, mode: str):
        self.root, self.apply, self.mode = root, apply, mode
        self.actions = []

    def _rel(self, p: Path) -> str:
        return p.relative_to(self.root).as_posix()

    def write_text(self, p: Path, text: str):
        if _read(p) == text and p.is_file() and not p.is_symlink():
            return
        self.actions.append({"op": "write", "path": self._rel(p)})
        if self.apply:
            if p.is_symlink():
                p.unlink()
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")

    def link_dir(self, dst: Path, src: Path):
        """dst 指向 src（目录）。link 模式建相对符号链接；copy 模式整目录镜像。"""
        if self.mode == "link":
            target = os.path.relpath(src, dst.parent)
            if dst.is_symlink() and os.readlink(dst) == target:
                return
            self.actions.append({"op": "link", "path": self._rel(dst), "target": target})
            if self.apply:
                self._remove(dst)
                dst.parent.mkdir(parents=True, exist_ok=True)
                os.symlink(target, dst, target_is_directory=True)
        else:
            if dst.is_dir() and not dst.is_symlink() and _tree_equal(src, dst):
                return
            self.actions.append({"op": "copy", "path": self._rel(dst), "from": self._rel(src)})
            if self.apply:
                self._remove(dst)
                shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
                (dst / GENERATED_FILE).write_text("directory-copy\n", encoding="utf-8")

    def link_file(self, dst: Path, src: Path):
        if self.mode == "link":
            target = os.path.relpath(src, dst.parent)
            if dst.is_symlink() and os.readlink(dst) == target:
                return
            self.actions.append({"op": "link", "path": self._rel(dst), "target": target})
            if self.apply:
                self._remove(dst)
                dst.parent.mkdir(parents=True, exist_ok=True)
                os.symlink(target, dst)
        else:
            if dst.is_file() and not dst.is_symlink() and dst.read_bytes() == src.read_bytes():
                return
            self.actions.append({"op": "copy", "path": self._rel(dst), "from": self._rel(src)})
            if self.apply:
                self._remove(dst)
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src, dst)

    def remove(self, p: Path, why: str):
        if not (p.exists() or p.is_symlink()):
            return
        self.actions.append({"op": "remove", "path": self._rel(p), "why": why})
        if self.apply:
            self._remove(p)

    @staticmethod
    def _remove(p: Path):
        if p.is_symlink() or p.is_file():
            p.unlink()
        elif p.is_dir():
            shutil.rmtree(p)


def _tree_equal(a: Path, b: Path) -> bool:
    def files(base):
        return {f.relative_to(base).as_posix(): f for f in base.rglob("*")
                if f.is_file() and "__pycache__" not in f.parts and f.suffix != ".pyc"
                and f.name != GENERATED_FILE}
    fa, fb = files(a), files(b)
    if fa.keys() != fb.keys():
        return False
    return all(fa[k].read_bytes() == fb[k].read_bytes() for k in fa)


# ── 记忆文件 ──────────────────────────────────────────────────────────────────
def sync_memory(plan: Plan, agents: list):
    root = plan.root
    agents_md, claude_md = root / "AGENTS.md", root / "CLAUDE.md"
    a_txt, c_txt = _read(agents_md), _read(claude_md)
    c_body = c_txt if (c_txt and not _is_shell(c_txt)) else ""
    a_body = a_txt if (a_txt and not _is_shell(a_txt)) else ""
    only_claude = agents == ["claude"]

    if only_claude:
        if c_body:
            return  # 正文已在 CLAUDE.md
        if a_body:
            # 正文在 AGENTS.md：保持单一正文，CLAUDE.md 做导入薄壳（Claude Code 读 CLAUDE.md）
            plan.write_text(claude_md, SHELL_BODY)
        return

    # 存在非 Claude Agent：正文必须在 AGENTS.md
    if not a_body and c_body:
        plan.write_text(agents_md, c_body)  # 搬正文，⛔ 不丢
        a_body = c_body
    if "claude" in agents and a_body:
        plan.write_text(claude_md, SHELL_BODY)


# ── 原生命令与 SKILL 入口 ────────────────────────────────────────────────────
def _command_files(root: Path) -> list:
    src = root / AIDP_DIR / "commands"
    if not src.is_dir():
        return []
    return [p for p in sorted(src.glob("*.md")) if p.stem.upper() != "README"]


def _command_description(name: str, text: str) -> str:
    frontmatter = _frontmatter(text)
    if frontmatter.get("description"):
        return frontmatter["description"].replace('"', "'")
    match = re.search(r"^#\s+(.+?)\s*$", text, re.M)
    return (match.group(1).strip() if match else f"AIDP command {name}").replace('"', "'")


def _codex_command_preamble(name: str) -> str:
    return (
        "## Codex 命令适配规则\n\n"
        f"1. 用户以 `${name} args` 调用本命令时，`args` 的全部文字原样作为本命令的 `$ARGUMENTS`；"
        "不增删、不改写、不调整顺序与引号。\n"
        "2. 当下方原始命令正文明确调用或串联 `/foo args` 时，不依赖隐式 SKILL 调用，而是读取 "
        "`.aidp/commands/<命令名>.md`（此处命令名为 `foo`）。确认文件存在后，将 `args` 原样作为"
        "子命令的 `$ARGUMENTS`，在当前执行链内联执行。\n"
        "3. 被引用的命令文件不存在、命令名未知或无法唯一映射时，必须 fail closed：停止执行并报告未知命令，严禁猜测或跳过。\n"
        "4. 本适配层只负责参数传递和命令串联；不得改写下方原始命令正文。\n\n"
    )


def codex_command_skill(name: str, command_text: str) -> str:
    return (
        "---\n"
        f"name: {name}\n"
        f'description: "{_command_description(name, command_text)}"\n'
        "disable-model-invocation: true\n"
        "user-invocable: true\n"
        "---\n\n"
        f"{_codex_command_preamble(name)}"
        f"{CODEX_BODY_MARKER}"
        f"{command_text}"
    )


def _is_generated(p: Path) -> bool:
    if p.is_symlink():
        return AIDP_DIR in os.readlink(p)
    if p.is_dir():
        skill_text = _read(p / "SKILL.md")
        return ((p / GENERATED_FILE).is_file() or GENERATED_MARK in skill_text
                or "命令表由 .aidp/scripts/agent_sync.py" in skill_text)
    return GENERATED_MARK in _read(p) or (p.name == "marketplace.json" and _read(p.parent / GENERATED_FILE) == "marketplace\n")


def _prune(plan: Plan, base: Path, wanted: set):
    """只遍历 root 内无 symlink 祖先的真实目录，绝不跨越适配边界。"""
    try:
        relative = base.relative_to(plan.root)
    except ValueError:
        return
    current = plan.root
    for part in relative.parts:
        current = current / part
        if current.is_symlink():
            return
    if not base.is_dir():
        return
    for p in sorted(base.iterdir()):
        if p.name not in wanted and _is_generated(p):
            plan.remove(p, "not generated anymore")


def _require_generated_or_absent(path: Path, label: str):
    if (path.exists() or path.is_symlink()) and not _is_generated(path):
        raise SystemExit(f"[agent_sync] {label} 已存在用户内容，拒绝覆盖：{path}")


def _base_skill_dirs(root: Path) -> dict:
    source = root / AIDP_DIR / "skills"
    if not source.is_dir():
        return {}
    return {p.name: p for p in sorted(source.iterdir())
            if p.name != OBSOLETE_ROUTER and (p / "SKILL.md").is_file()}


def sync_skill_dir(plan: Plan, rel: str, extra: dict = None) -> list:
    skills = _base_skill_dirs(plan.root)
    for name, source in (extra or {}).items():
        if name in skills:
            raise SystemExit(f"[agent_sync] 插件 SKILL 与公共 SKILL 同名冲突：{name}")
        skills[name] = source
    generated = []
    destination = plan.root / rel
    for name, source in sorted(skills.items()):
        target = destination / name
        _require_generated_or_absent(target, "SKILL 入口")
        plan.link_dir(target, source)
        generated.append(f"{rel}/{name}")
    _prune(plan, destination, set(skills))
    return generated


def _generated_names(path: Path) -> set:
    try:
        data = json.loads(_read(path) or "[]")
    except json.JSONDecodeError:
        return set()
    return {str(item) for item in data if isinstance(item, str)} if isinstance(data, list) else set()


def sync_file_commands(plan: Plan, rel: str, enabled: bool = True) -> list:
    destination = plan.root / rel
    marker = destination / GENERATED_FILE
    previous = _generated_names(marker)
    commands = _command_files(plan.root) if enabled else []
    wanted = {command.name for command in commands}
    for name in sorted(previous - wanted):
        plan.remove(destination / name, "command source removed")
    generated = []
    for command in commands:
        target = destination / command.name
        if (target.exists() or target.is_symlink()) and command.name not in previous and not _is_generated(target):
            raise SystemExit(f"[agent_sync] 原生命令目标已存在用户内容，拒绝覆盖：{target}")
        plan.link_file(target, command)
        generated.append(f"{rel}/{command.name}")
    if wanted:
        plan.write_text(marker, json.dumps(sorted(wanted), ensure_ascii=False) + "\n")
        generated.append(f"{rel}/{GENERATED_FILE}")
    elif marker.is_file():
        plan.remove(marker, "no generated commands")
    return generated


def sync_codex_commands(plan: Plan) -> list:
    destination = plan.root / CODEX_COMMAND_SKILLS
    wanted = set()
    generated = []
    for command in _command_files(plan.root):
        name = command.stem
        target = destination / name
        _require_generated_or_absent(target, "Codex 命令 SKILL")
        wanted.add(name)
        plan.write_text(target / "SKILL.md", codex_command_skill(name, _read(command)))
