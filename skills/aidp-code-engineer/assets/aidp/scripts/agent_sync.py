# ── 通用小工具 ────────────────────────────────────────────────────────────────
def _read(p: Path) -> str:
    try:
        return p.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return ""


def _frontmatter(text: str) -> dict:
    """只解析 `key: value` 单行形式，够读 description / argument-hint。"""
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n", text, re.S)
    out = {}
    if not m:
        return out
    for line in m.group(1).splitlines():
        kv = re.match(r"^([A-Za-z_-]+)\s*:\s*(.*)$", line)
        if kv:
            out[kv.group(1)] = kv.group(2).strip().strip('"').strip("'")
    return out


def _title_description(text: str) -> str:
    """命令文件无 frontmatter 时，取首个 H1「# /name — 说明」里破折号后的说明（去掉标题装饰符 ★）。"""
    m = re.search(r"^#\s+/?[\w-]+\s*[—-]+\s*(.+?)\s*$", text, re.M)
    if not m:
        return ""
    desc = re.sub(r"[（(]\s*★\s*[)）]|★", "", m.group(1)).strip()
    return f"AIDP 命令：{desc}"


def _is_shell(text: str) -> bool:
    body = [l for l in text.splitlines() if l.strip() and not l.strip().startswith("<!--")]
    return len(body) == 1 and body[0].strip() == "@AGENTS.md"


def _lexical(path: Path) -> Path:
    return Path(os.path.abspath(os.path.normpath(os.fspath(path))))


def _source_boundary(root: Path, source: Path) -> Path:
    root_abs = _lexical(root)
    source_abs = _lexical(source)
    candidates = (RUNTIME_ROOT, root / ("." + "aidp"),
                  root / AGENT_RUNTIME_HOME["claude"], root / AGENT_RUNTIME_HOME["codex"])
    for candidate in candidates:
        boundary = _lexical(candidate)
        try:
            boundary.relative_to(root_abs)
            source_abs.relative_to(boundary)
            return boundary
        except ValueError:
            continue
    raise SystemExit(f"[agent_sync] 复制源路径越出 AIDP 运行包：{source}")


def _validate_real_chain(root: Path, target: Path):
    root_abs = _lexical(root)
    target_abs = _lexical(target)
    try:
        parts = target_abs.relative_to(root_abs).parts
    except ValueError as exc:
        raise SystemExit(f"[agent_sync] 复制源路径越出项目根：{target}") from exc
    current = root_abs
    try:
        root_info = current.lstat()
    except OSError as exc:
        raise SystemExit(f"[agent_sync] 项目根不存在：{current}：{exc}")
    if stat.S_ISLNK(root_info.st_mode) or not stat.S_ISDIR(root_info.st_mode):
        raise SystemExit(f"[agent_sync] 项目根必须是实体目录：{current}")
    for part in parts:
        current = current / part
        try:
            info = current.lstat()
        except OSError as exc:
            raise SystemExit(f"[agent_sync] 复制源不存在：{current}：{exc}")
        if stat.S_ISLNK(info.st_mode):
            raise SystemExit(f"[agent_sync] 复制源祖先包含 symlink：{current}")
        if not stat.S_ISDIR(info.st_mode):
            raise SystemExit(f"[agent_sync] 复制源祖先不是目录：{current}")


def _validate_material_path(root: Path, source: Path, expect_dir: bool):
    """从可信项目根开始，不跟随链接地验证复制源。"""
    boundary = _source_boundary(root, source)
    source_abs = _lexical(source)
    _validate_real_chain(root, boundary)
    if source_abs != boundary:
        _validate_real_chain(root, source_abs.parent)

    info = source_abs.lstat()
    if expect_dir and not stat.S_ISDIR(info.st_mode):
        raise SystemExit(f"[agent_sync] 复制源必须是目录：{source_abs}")
    if not expect_dir:
        if not stat.S_ISREG(info.st_mode):
            raise SystemExit(f"[agent_sync] 复制源必须是普通文件：{source_abs}")
        if info.st_nlink != 1:
            raise SystemExit(f"[agent_sync] 复制源文件存在硬链接：{source_abs}")
        return

    for dirpath, dirnames, filenames in os.walk(source_abs, followlinks=False):
        base = Path(dirpath)
        for name in list(dirnames) + list(filenames):
            path = base / name
            child = path.lstat()
            if stat.S_ISLNK(child.st_mode):
                raise SystemExit(f"[agent_sync] 复制源包含 symlink：{path}")
            if name in dirnames:
                if not stat.S_ISDIR(child.st_mode):
                    raise SystemExit(f"[agent_sync] 复制源包含非目录节点：{path}")
            else:
                if not stat.S_ISREG(child.st_mode):
                    raise SystemExit(f"[agent_sync] 复制源包含非普通文件：{path}")
                if child.st_nlink != 1:
                    raise SystemExit(f"[agent_sync] 复制源文件存在硬链接：{path}")


def _file_record(path: Path) -> dict:
    info = path.lstat()
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise SystemExit(f"[agent_sync] 受管文件不是单链接普通文件，冲突：{path}")
    return {"sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "mode": format(info.st_mode & 0o777, "04o")}


def _directory_inventory(root: Path) -> dict:
    if root.is_symlink() or not root.is_dir():
        raise SystemExit(f"[agent_sync] 受管目录不是实体目录，冲突：{root}")
    entries = {".": {"type": "dir", "mode": format(root.lstat().st_mode & 0o777, "04o")}}
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        base = Path(dirpath)
        for name in sorted(dirnames + filenames):
            path = base / name
            if path == root / GENERATED_FILE:
                continue
            info = path.lstat()
            rel = path.relative_to(root).as_posix()
            if stat.S_ISDIR(info.st_mode):
                entries[rel] = {"type": "dir", "mode": format(info.st_mode & 0o777, "04o")}
            elif stat.S_ISREG(info.st_mode) and info.st_nlink == 1:
                entries[rel] = {"type": "file", **_file_record(path)}
            else:
                raise SystemExit(f"[agent_sync] 受管目录包含非实体或硬链接节点，冲突：{path}")
    return entries


def _directory_marker(root: Path) -> str:
    return json.dumps({"schema": "aidp.adapter/v1", "entries": _directory_inventory(root)},
                      ensure_ascii=False, sort_keys=True) + "\n"


def _check_managed_directory(path: Path, source: Path = None):
    if path.is_symlink():
        return
    marker = path / GENERATED_FILE
    try:
        data = json.loads(_read(marker))
    except (ValueError, TypeError):
        data = None
    current = _directory_inventory(path)
    if (path.parent.name == "plugins" and path.parent.parent.name == ".agents"
            and _read(marker) == "" and set(current) == {".", "plugin.json"}):
        try:
            legacy = json.loads(_read(path / "plugin.json"))
        except json.JSONDecodeError:
            legacy = None
        if legacy == {"name": path.name}:
            return
    if isinstance(data, dict) and data.get("schema") == "aidp.adapter/v1":
        if data.get("entries") != current:
            raise SystemExit(f"[agent_sync] 受管目录已被修改或追加，冲突：{path}")
        return
    if _read(marker) != "directory-copy\n" or source is None or not _tree_equal(source, path):
        raise SystemExit(f"[agent_sync] 旧受管目录无有效清单且内容不一致，冲突：{path}")


def _validate_staged_tree(stage: Path):
    info = stage.lstat()
    if not stat.S_ISDIR(info.st_mode) or stat.S_ISLNK(info.st_mode):
        raise SystemExit(f"[agent_sync] 临时目录不是实体目录：{stage}")
    for dirpath, dirnames, filenames in os.walk(stage, followlinks=False):
        base = Path(dirpath)
        for name in list(dirnames) + list(filenames):
            path = base / name
            child = path.lstat()
            if stat.S_ISLNK(child.st_mode):
                raise SystemExit(f"[agent_sync] 临时副本包含 symlink：{path}")
            if name in dirnames:
                if not stat.S_ISDIR(child.st_mode):
                    raise SystemExit(f"[agent_sync] 临时副本包含非目录节点：{path}")
            elif not stat.S_ISREG(child.st_mode) or child.st_nlink != 1:
                raise SystemExit(f"[agent_sync] 临时副本包含非普通或硬链接文件：{path}")


class Plan:
    """收集动作；apply=False 时只记录不落盘。"""

    def __init__(self, root: Path, apply: bool, mode: str):
        self.root, self.apply = root, apply
        self.requested_mode = mode
        self.mode = "copy"
        self.actions = []
        if mode == "link":
            self.actions.append({"op": "normalized", "action": "normalized", "path": "",
                                 "from": "link", "to": "managed-copy"})

    @property
    def drift(self) -> bool:
        return any(action.get("op") not in (None, "normalized") for action in self.actions)

    def _rel(self, p: Path) -> str:
        return p.relative_to(self.root).as_posix()

    def write_text(self, p: Path, text: str):
        if _read(p) == text and p.is_file() and not p.is_symlink() and p.stat().st_nlink == 1:
            return
        self.actions.append({"op": "write", "path": self._rel(p)})
        if self.apply:
            p.parent.mkdir(parents=True, exist_ok=True)
            fd, raw = tempfile.mkstemp(prefix=f".{p.name}.stage-", dir=str(p.parent))
            os.close(fd)
            stage = Path(raw)
            try:
                # ⛔ 不用 write_text：Windows 文本模式会把 \n 写成 \r\n，与真源 LF 字节比较必然假漂移。
                stage.write_bytes(text.encode("utf-8"))
                os.chmod(stage, 0o644)
                info = stage.lstat()
                if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                    raise SystemExit(f"[agent_sync] 临时文件不是单链接普通文件：{stage}")
                self._atomic_replace(p, stage)
            finally:
                if os.path.lexists(stage):
                    self._remove(stage)

    def link_dir(self, dst: Path, src: Path):
        """兼容旧调用名；新布局始终生成带标记的实体目录副本。"""
        _validate_material_path(self.root, src, expect_dir=True)
        if os.path.lexists(dst) and not dst.is_symlink():
            _check_managed_directory(dst, src)
        if dst.is_dir() and not dst.is_symlink() and _tree_equal(src, dst):
            if _read(dst / GENERATED_FILE) == _directory_marker(dst):
                return
            self.write_text(dst / GENERATED_FILE, _directory_marker(dst))
            return
        self.actions.append({"op": "copy", "path": self._rel(dst), "from": self._source_label(src)})
        if self.apply:
            dst.parent.mkdir(parents=True, exist_ok=True)
            stage = Path(tempfile.mkdtemp(prefix=f".{dst.name}.stage-", dir=str(dst.parent)))
            try:
                shutil.copytree(src, stage, symlinks=True, dirs_exist_ok=True,
                                ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
                (stage / GENERATED_FILE).write_bytes(_directory_marker(stage).encode("utf-8"))
                _validate_material_path(self.root, src, expect_dir=True)
                _validate_staged_tree(stage)
                if not _tree_equal(src, stage):
                    raise SystemExit("[agent_sync] 复制期间源目录发生变化，拒绝替换")
                self._atomic_replace(dst, stage)
            finally:
                if os.path.lexists(stage):
                    self._remove(stage)

    def link_file(self, dst: Path, src: Path):
        """兼容旧调用名；新布局始终生成保留 mode 的实体文件副本。"""
        _validate_material_path(self.root, src, expect_dir=False)
        if (dst.is_file() and not dst.is_symlink() and dst.stat().st_nlink == 1
                and dst.read_bytes() == src.read_bytes()
                and (dst.stat().st_mode & 0o777) == (src.stat().st_mode & 0o777)):
            return
        self.actions.append({"op": "copy", "path": self._rel(dst), "from": self._source_label(src)})
        if self.apply:
            dst.parent.mkdir(parents=True, exist_ok=True)
            fd, raw = tempfile.mkstemp(prefix=f".{dst.name}.stage-", dir=str(dst.parent))
            os.close(fd)
            stage = Path(raw)
            try:
                shutil.copy2(src, stage, follow_symlinks=False)
                _validate_material_path(self.root, src, expect_dir=False)
                info = stage.lstat()
                source_info = src.lstat()
                if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
                    raise SystemExit(f"[agent_sync] 临时文件不是单链接普通文件：{stage}")
                if (source_info.st_nlink != 1 or stage.read_bytes() != src.read_bytes()
                        or (info.st_mode & 0o777) != (source_info.st_mode & 0o777)):
                    raise SystemExit("[agent_sync] 复制期间源文件发生变化，拒绝替换")
                self._atomic_replace(dst, stage)
            finally:
                if os.path.lexists(stage):
                    self._remove(stage)

    def _atomic_replace(self, dst: Path, stage: Path):
        had_previous = os.path.lexists(dst)
        previous = None
        installed = False
        try:
            if had_previous:
                fd, raw = tempfile.mkstemp(
                    prefix=f".{dst.name}.previous-", dir=str(dst.parent))
                os.close(fd)
                previous = Path(raw)
                previous.unlink()
                os.replace(dst, previous)
            try:
                os.replace(stage, dst)
                installed = True
            except Exception:
                if had_previous and previous is not None and os.path.lexists(previous):
                    os.replace(previous, dst)
                raise
        finally:
            if not installed and not os.path.lexists(dst) and had_previous \
                    and previous is not None and os.path.lexists(previous):
                os.replace(previous, dst)
            if previous is not None and os.path.lexists(previous):
                self._remove(previous)

    def _source_label(self, src: Path) -> str:
        try:
            return src.relative_to(self.root).as_posix()
        except ValueError:
            try:
                return "AIDP_HOME/" + src.relative_to(RUNTIME_ROOT).as_posix()
            except ValueError:
                return str(src)

    def remove(self, p: Path, why: str):
        if not (p.exists() or p.is_symlink()):
            return
        if p.is_dir() and not p.is_symlink() and (p / GENERATED_FILE).is_file():
            _check_managed_directory(p)
        self.actions.append({"op": "remove", "path": self._rel(p), "why": why})
        if self.apply:
            self._remove(p)

    @staticmethod
    def _remove(p: Path):
        if p.is_symlink() or p.is_file():
            p.unlink()
        elif p.is_dir():
            shutil.rmtree(p)


def _tree_equal(a: Path, b: Path) -> bool:
    def inventory(base):
        directories = {}
        files = {}
        for path in base.rglob("*"):
            rel = path.relative_to(base)
            if "__pycache__" in rel.parts or path.suffix == ".pyc" or path.name == GENERATED_FILE:
                continue
            if path.is_symlink():
                return None
            key = rel.as_posix()
            info = path.stat()
            mode = info.st_mode & 0o777
            if path.is_dir():
                directories[key] = mode
            elif path.is_file():
                if info.st_nlink != 1:
                    return None
                files[key] = (mode, path.read_bytes())
            else:
                return None
        return directories, files

    left = inventory(a)
    right = inventory(b)
    return left is not None and right is not None and left == right


# ── 记忆文件 ──────────────────────────────────────────────────────────────────
def sync_memory(plan: Plan, agents: list):
    root = plan.root
    agents_md, claude_md = root / "AGENTS.md", root / "CLAUDE.md"
    a_txt, c_txt = _read(agents_md), _read(claude_md)
    c_body = c_txt if (c_txt and not _is_shell(c_txt)) else ""
    a_body = a_txt if (a_txt and not _is_shell(a_txt)) else ""
    only_claude = agents == ["claude"]

    if only_claude:
        if c_body:
            return  # 正文已在 CLAUDE.md
        if a_body:
            # 正文在 AGENTS.md：保持单一正文，CLAUDE.md 做导入薄壳（Claude Code 读 CLAUDE.md）
            plan.write_text(claude_md, SHELL_BODY)
        return

    # 存在非 Claude Agent：正文必须在 AGENTS.md
    if not a_body and c_body:
        plan.write_text(agents_md, c_body)  # 搬正文，⛔ 不丢
        a_body = c_body
    if "claude" in agents and a_body:
        plan.write_text(claude_md, SHELL_BODY)


