def _declared_skill_names(skills: dict) -> set:
    return {_frontmatter(_read(_skill_entry(path) or path / "SKILL.md")).get("name") or path.name
            for path in skills.values()}


def _name_conflicts(root: Path, plugin_skills: dict) -> list:
    skills = _declared_skill_names(_base_skill_dirs(root)) | set(plugin_skills)
    commands = {path.stem for path in _command_files(root)}
    return sorted(skills & commands)


def _json_object(path: Path, label: str) -> dict:
    try:
        value = json.loads(_read(path) or "{}")
    except json.JSONDecodeError as exc:
        raise SystemExit(f"[agent_sync] {label} JSON 非法：{exc}")
    if not isinstance(value, dict):
        raise SystemExit(f"[agent_sync] {label} 类型错误：顶层必须是对象")
    return value


def _validate_hook_structure(data: dict, path: Path):
    hooks = data.get("hooks", {})
    if not isinstance(hooks, dict):
        raise SystemExit(f"[agent_sync] hooks 结构错误：{path} 的 hooks 必须是对象")
    stop = hooks.get("Stop", [])
    if not isinstance(stop, list):
        raise SystemExit(f"[agent_sync] hooks 结构错误：{path} 的 Stop 必须是数组")
    for index, group in enumerate(stop):
        if not isinstance(group, dict):
            raise SystemExit(f"[agent_sync] hooks 结构错误：{path} Stop[{index}] 必须是对象")
        entries = group.get("hooks", [])
        if not isinstance(entries, list):
            raise SystemExit(f"[agent_sync] hooks 结构错误：{path} Stop[{index}].hooks 必须是数组")
        for hook_index, hook in enumerate(entries):
            if not isinstance(hook, dict):
                raise SystemExit(
                    f"[agent_sync] hooks 结构错误：{path} Stop[{index}].hooks[{hook_index}] 必须是对象")
            if "command" in hook and not isinstance(hook["command"], str):
                raise SystemExit(f"[agent_sync] hooks 结构错误：{path} command 必须是字符串")
            if "type" in hook and not isinstance(hook["type"], str):
                raise SystemExit(f"[agent_sync] hooks 结构错误：{path} type 必须是字符串")


def _validate_codex_features(root: Path):
    path = root / ".codex/config.toml"
    text = _read(path)
    feature_headers = list(re.finditer(r"(?m)^[ \t]*\[features\][ \t]*$", text))
    assignments = list(re.finditer(r"(?m)^[ \t]*codex_hooks[ \t]*=.*$", text))
    hook_keys = list(CODEX_HOOK_LINE_RE.finditer(text))
    if len(feature_headers) > 1:
        raise SystemExit(f"[agent_sync] Codex features 结构错误：{path} 含重复 [features] section")
    if len(assignments) > 1:
        raise SystemExit(f"[agent_sync] Codex features 结构错误：{path} 含重复 codex_hooks 键")
    if assignments and not hook_keys:
        raise SystemExit(f"[agent_sync] Codex features 结构错误：codex_hooks 必须是 true/false")
    if hook_keys:
        if not feature_headers:
            raise SystemExit(f"[agent_sync] Codex features 结构错误：codex_hooks 不在 [features] section")
        start = feature_headers[0].end()
        next_header = re.search(r"(?m)^[ \t]*\[", text[start:])
        end = start + next_header.start() if next_header else len(text)
        if not (start <= hook_keys[0].start() < end):
            raise SystemExit(f"[agent_sync] Codex features 结构错误：codex_hooks 不在 [features] section")


def _merge_codex_hook_flag(text: str) -> str:
    if CODEX_HOOK_LINE_RE.search(text):
        def replace(match):
            return (f"{match.group('indent')}codex_hooks{match.group('before')}="
                    f"{match.group('after')}true{match.group('comment')}")
        return CODEX_HOOK_LINE_RE.sub(replace, text, count=1)
    if re.search(r"(?m)^[ \t]*\[features\][ \t]*$", text):
        return re.sub(r"(?m)^([ \t]*\[features\][ \t]*)$", r"\1\ncodex_hooks = true", text, count=1)
    return (text.rstrip() + "\n\n" if text.strip() else "") + "[features]\ncodex_hooks = true\n"


def _validate_hooks(root: Path, agents: list):
    if not STOP_GUARD_SOURCE.is_file():
        return
    paths = {"claude": root / ".claude/settings.json",
             "codex": root / ".codex/hooks.json",
             "dsh": root / ".dsh/hooks.json"}
    for agent in agents:
        path = paths[agent]
        data = _json_object(path, f"{agent} hooks {path}") if path.exists() else {}
        _validate_hook_structure(data, path)
        _merge_stop_hook(json.loads(json.dumps(data)), _hook_cmd(agent), root)
    if "codex" in agents:
        _validate_codex_features(root)


def _validate_claude_plugins(root: Path, plugins: list):
    marker_path = root / CLAUDE_PLUGIN_MANAGED
    settings_path = root / ".claude/settings.json"
    if not plugins and not marker_path.is_file():
        return
    settings = _json_object(settings_path, "Claude settings")
    marker = _json_object(marker_path, "Claude plugin marker") if marker_path.is_file() else {}
    for field in ("marketplaces", "enabledPlugins"):
        values = marker.get(field, [])
        if not isinstance(values, list) or any(not isinstance(item, str) for item in values):
            raise SystemExit(f"[agent_sync] Claude plugin marker 字段类型错误：{field}")
    markets = settings.get("extraKnownMarketplaces", {})
    enabled = settings.get("enabledPlugins", {})
    if not isinstance(markets, dict):
        raise SystemExit("[agent_sync] Claude settings 字段类型错误：extraKnownMarketplaces 必须是对象")
    if not isinstance(enabled, dict):
        raise SystemExit("[agent_sync] Claude settings 字段类型错误：enabledPlugins 必须是对象")
    markets = dict(markets)
    enabled = dict(enabled)
    for key in marker.get("marketplaces", []):
        markets.pop(key, None)
    for key in marker.get("enabledPlugins", []):
        enabled.pop(key, None)

    for plugin in plugins:
        marketplace_path = plugin / ".claude-plugin/marketplace.json"
        marketplace = _json_object(marketplace_path, f"Claude marketplace {marketplace_path}") \
            if marketplace_path.is_file() else {}
        name = marketplace.get("name") or f"{plugin.name}-marketplace"
        entries = marketplace.get("plugins", [{"name": plugin.name}])
        if not isinstance(name, str) or not isinstance(entries, list) \
                or any(not isinstance(entry, dict) for entry in entries):
            raise SystemExit(f"[agent_sync] Claude marketplace 字段类型错误：{marketplace_path}")
        desired = {"source": {"source": "directory", "path": f"./{CLAUDE_PLUGINS}/{plugin.name}"}}
        if name in markets and markets[name] != desired:
            raise SystemExit(f"[agent_sync] Claude marketplace 用户配置冲突：{name}")
        for entry in entries:
            plugin_name = entry.get("name", plugin.name)
            if not isinstance(plugin_name, str):
                raise SystemExit(f"[agent_sync] Claude marketplace 字段类型错误：{marketplace_path}")
            key = f"{plugin_name}@{name}"
            if key in enabled and enabled[key] is not True:
                raise SystemExit(f"[agent_sync] Claude enabledPlugins 用户配置冲突：{key}")


def _validate_real_namespace(root: Path, rel: str, label: str):
    current = root
    for part in Path(rel).parts:
        current = current / part
        if current.is_symlink():
            raise SystemExit(f"[agent_sync] {label} 必须位于真实目录，拒绝 symlink：{current}")
        if current.exists() and not current.is_dir():
            raise SystemExit(f"[agent_sync] {label} 必须位于真实目录，发现非目录：{current}")


def _validate_adapter_namespaces(root: Path, plugins: list):
    namespaces = {
        ".claude", CLAUDE_SKILLS, CLAUDE_COMMANDS, CLAUDE_PLUGINS,
        ".codex", CODEX_PLUGIN_SKILLS, CODEX_COMMAND_SKILLS,
        ".dsh", DSH_COMMANDS, ".dsh/skills",
        ".agents", SHARED_SKILLS, LEGACY_CODEX_PLUGINS,
    }
    namespaces.update(f"{SHARED_SKILLS}/{plugin.name}" for plugin in plugins
                      if (plugin / "skills").is_dir())
    for rel in sorted(namespaces, key=lambda item: (len(Path(item).parts), item)):
        _validate_real_namespace(root, rel, f"Agent 适配 namespace {rel}")


def _has_managed_marker(path: Path) -> bool:
    try:
        return (path / GENERATED_FILE).is_file()
    except OSError as exc:
        raise SystemExit(f"[agent_sync] 受管目录无法检查，冲突：{path}：{exc}") from exc


def _validate_existing_managed(root: Path, agents: list, plugins: list):
    skills = _base_skill_dirs(root)
    for rel in (CLAUDE_SKILLS, SHARED_SKILLS):
        base = root / rel
        if not base.is_dir() or base.is_symlink():
            continue
        for target in base.iterdir():
            if target.is_symlink() or not _has_managed_marker(target):
                continue
            source = skills.get(target.name)
            plugin = next((item for item in plugins if item.name == target.name), None)
            if plugin is not None and rel == SHARED_SKILLS and (plugin / "skills").is_dir():
                source = plugin / "skills"
                if _read(target / GENERATED_FILE) == "plugin-skills\n":
                    if not _tree_equal(source, target / "skills"):
                        raise SystemExit(f"[agent_sync] 旧插件目录被修改，冲突：{target}")
                    continue
                if (target / "skills" / GENERATED_FILE).is_file():
                    _check_managed_directory(target / "skills", source)
                source = None
            if source is None and _read(target / GENERATED_FILE) == "directory-copy\n":
                raise SystemExit(f"[agent_sync] 旧受管目录源已删除，无法验证，冲突：{target}")
            _check_managed_directory(target, source)
    plugin_by_name = {plugin.name: plugin for plugin in plugins}
    for rel, sources in ((CLAUDE_PLUGINS, plugin_by_name),):
        base = root / rel
        if base.is_dir() and not base.is_symlink():
            for target in base.iterdir():
                if target.is_dir() and not target.is_symlink() and _has_managed_marker(target):
                    _check_managed_directory(target, sources.get(target.name))
    for rel in (CLAUDE_COMMANDS, DSH_COMMANDS):
        base = root / rel
        marker = base / GENERATED_FILE
        if not marker.is_file():
            continue
        ledger = _command_ledger(marker)
        sources = {command.name: command for command in _command_files(root)}
        for name, record in ledger.items():
            target = base / name
            if os.path.lexists(target):
                _check_command(root, target, record, sources.get(name))
            elif name not in sources:
                raise SystemExit(f"[agent_sync] 受管命令缺失，冲突：{target}")
    base = root / CODEX_COMMAND_SKILLS
    if base.is_dir() and not base.is_symlink():
        sources = {command.stem: command for command in _command_files(root)}
        for target in base.iterdir():
            if not target.is_dir() or target.is_symlink() or not _has_managed_marker(target):
                continue
            marker = _read(target / GENERATED_FILE)
            if marker == "native-command\n":
                command = sources.get(target.name)
                if command is None or _read(target / "SKILL.md") != codex_command_skill(target.name, _read(command)) \
                        or _read(target / "agents/openai.yaml") != OPENAI_YAML \
                        or any(p.relative_to(target).as_posix() not in
                               {GENERATED_FILE, "SKILL.md", "agents", "agents/openai.yaml"}
                               for p in target.rglob("*")):
                    raise SystemExit(f"[agent_sync] 旧 Codex 命令被修改，冲突：{target}")
            else:
                _check_managed_directory(target)


def _validate_targets(root: Path, agents: list, plugins: list, plugin_skills: dict):
    if "claude" in agents:
        for name in _base_skill_dirs(root):
            _require_generated_or_absent(root, root / CLAUDE_SKILLS / name, "Claude SKILL 入口")
        destination = root / CLAUDE_COMMANDS
        previous = _generated_names(destination / GENERATED_FILE)
        for command in _command_files(root):
            target = destination / command.name
            if (target.exists() or target.is_symlink()) and command.name not in previous:
                if not _is_generated(target, root):
                    raise SystemExit(f"[agent_sync] Claude 命令目标已存在用户内容，拒绝覆盖：{target}")
                _check_command(root, target, None, command)
        for plugin in plugins:
            _require_generated_or_absent(root, root / CLAUDE_PLUGINS / plugin.name,
                                         "Claude 插件目录")
    if "codex" in agents:
        for command in _command_files(root):
            _require_generated_or_absent(root, root / CODEX_COMMAND_SKILLS / command.stem,
                                         "Codex 命令 SKILL")
    if "dsh" in agents:
        destination = root / DSH_COMMANDS
        previous = _generated_names(destination / GENERATED_FILE)
        for command in _command_files(root):
            target = destination / command.name
            if (target.exists() or target.is_symlink()) and command.name not in previous:
                if not _is_generated(target, root):
                    raise SystemExit(f"[agent_sync] 原生命令目标已存在用户内容，拒绝覆盖：{target}")
                _check_command(root, target, None, command)
    if "codex" in agents or "dsh" in agents:
        for name in _base_skill_dirs(root):
            _require_generated_or_absent(root, root / SHARED_SKILLS / name, "SKILL 入口")
        for plugin in plugins:
            if (plugin / "skills").is_dir():
                _require_generated_or_absent(root, root / SHARED_SKILLS / plugin.name,
                                             "共享插件 SKILL namespace")


def run(root: Path, agents: list, mode: str, apply: bool) -> dict:
    global RUNTIME_ROOT
    shared_runtime = RUNTIME_ROOT
    claude_runtime = root / AGENT_RUNTIME_HOME["claude"]
    if not (claude_runtime / ".aidp-runtime.json").is_file():
        claude_runtime = shared_runtime
    plugins = _plugin_dirs(root)
    _validate_copy_sources(root, plugins)
    if "claude" in agents and claude_runtime != shared_runtime:
        RUNTIME_ROOT = claude_runtime
        try:
            claude_plugins = _plugin_dirs(root)
            _validate_copy_sources(root, claude_plugins)
        finally:
            RUNTIME_ROOT = shared_runtime
    else:
        claude_plugins = plugins
    plugin_skills = _plugin_skill_dirs(plugins) if ({"codex", "dsh"} & set(agents)) else {}
    public_skill_dirs = _base_skill_dirs(root)
    public_skills = _declared_skill_names(public_skill_dirs)
    plugins_with_skills = {plugin.name: plugin for plugin in plugins
                           if (plugin / "skills").is_dir()}
    path_clash = sorted(set(public_skill_dirs) & set(plugins_with_skills))
    if path_clash:
        details = "; ".join(
            f"{name}：{public_skill_dirs[name]}；{plugins_with_skills[name]}"
            for name in path_clash)
        raise SystemExit(f"[agent_sync] 共享 SKILL namespace 冲突：{details}")
    skill_clash = sorted(public_skills & set(plugin_skills))
    declared_namespace_clash = sorted(public_skills & set(plugins_with_skills))
    if skill_clash or declared_namespace_clash:
        names = sorted(set(skill_clash) | set(declared_namespace_clash))
        raise SystemExit(f"[agent_sync] 插件 SKILL 与公共 SKILL 同名冲突：{', '.join(names)}")
    clash = _name_conflicts(root, plugin_skills)
    if clash:
        raise SystemExit(f"[agent_sync] 命令与 SKILL 同名冲突：{', '.join(clash)}，请改名其一")
    all_servers = _plugin_servers(plugins)
    _validate_adapter_namespaces(root, plugins)
    _validate_existing_managed(root, agents, plugins)
    _validate_targets(root, agents, plugins, plugin_skills)
    if "claude" in agents and claude_runtime != shared_runtime:
        RUNTIME_ROOT = claude_runtime
        try:
            _validate_targets(root, ["claude"], claude_plugins, {})
        finally:
            RUNTIME_ROOT = shared_runtime
    _validate_hooks(root, agents)
    _validate_claude_plugins(root, claude_plugins if "claude" in agents else [])
    if "codex" in agents:
        _validate_codex_mcp(root, all_servers)
    if "dsh" in agents:
        _validate_dsh_mcp(root, all_servers)

    plan = Plan(root, apply, mode)
    sync_memory(plan, agents)
    for agent in agents:
        sync_hooks(plan, agent)
    legacy_plugins = cleanup_legacy_codex_plugins(plan)
    generated = []

    if "claude" in agents:
        RUNTIME_ROOT = claude_runtime
        try:
            generated += sync_skill_dir(plan, CLAUDE_SKILLS)
            generated += sync_file_commands(plan, CLAUDE_COMMANDS)
            generated += sync_claude_plugins(plan, claude_plugins)
        finally:
            RUNTIME_ROOT = shared_runtime
    else:
        _prune(plan, root / CLAUDE_SKILLS, set())
        sync_file_commands(plan, CLAUDE_COMMANDS, enabled=False)
        sync_claude_plugins(plan, [])

    shared_enabled = bool({"codex", "dsh"} & set(agents))
    plugin_names = {plugin.name for plugin in plugins if (plugin / "skills").is_dir()}
    if shared_enabled:
        generated += sync_skill_dir(plan, SHARED_SKILLS, preserve=plugin_names)
        generated += sync_shared_plugin_skills(plan, plugins)
    else:
        _prune(plan, root / SHARED_SKILLS, set())
        sync_shared_plugin_skills(plan, plugins, enabled=False)

    if "codex" in agents:
        generated += sync_codex_commands(plan)
        sync_codex_plugin_skills(plan, plugins)
        sync_codex_mcp(plan, all_servers, legacy_plugins)
    else:
        _prune(plan, root / CODEX_COMMAND_SKILLS, set())
        sync_codex_plugin_skills(plan, [])
        sync_codex_mcp(plan, {}, legacy_plugins)

    if "dsh" in agents:
        generated += sync_file_commands(plan, DSH_COMMANDS)
        generated += sync_dsh_mcp(plan, all_servers)
    else:
        sync_file_commands(plan, DSH_COMMANDS, enabled=False)
        generated += sync_dsh_mcp(plan, {})

    _prune(plan, root / LEGACY_CODEX_COMMAND_SKILLS, set())
    _prune(plan, root / ".dsh/skills", set())
    sync_gitignore(plan, generated)
    return {"agents": agents, "mode": "managed-copy", "applied": apply,
            "drift": plan.drift, "actions": plan.actions}


def _self_check() -> int:
    """黑盒验证原生运行包可独立生成三端 managed-copy 入口。"""
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        runtime = root / AGENT_RUNTIME_HOME["codex"]
        shutil.copytree(RUNTIME_ROOT, runtime,
                        ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "tests"))
        (root / "CLAUDE.md").write_bytes("# 正文\n".encode("utf-8"))
        (root / ".gitignore").write_bytes(b"node_modules/\n")
        for directory in (".claude", ".codex", ".dsh"):
            (root / directory).mkdir()

        script = runtime / "scripts/agent_sync.py"
        env = dict(os.environ, AIDP_PROJECT_ROOT=str(root), AIDP_HOME=str(runtime))

        def invoke(*extra):
            cp = subprocess.run(
                [sys.executable, str(script), "--root", str(root),
                 "--agents", "claude,codex,dsh", *extra],
                capture_output=True, text=True, env=env, timeout=60,
            )
            try:
                payload = json.loads(cp.stdout.strip().splitlines()[-1])
            except (ValueError, IndexError):
                payload = {}
            return cp.returncode, payload

        command = next((p.stem for p in sorted((runtime / "commands").glob("*.md"))
                        if p.stem.upper() != "README"), "")
        skill = next((p.name for p in sorted((runtime / "skills").iterdir())
                      if p.name != "aidp-code-engineer" and (p / "SKILL.md").is_file()), "")
        plugin = next((p for p in sorted((runtime / "plugins").iterdir())
                       if (p / "skills").is_dir()), None)
        plugin_skill = (next((p.name for p in sorted((plugin / "skills").iterdir())
                              if (p / "SKILL.md").is_file()), "") if plugin else "")

        first_rc, first = invoke("--mode", "link")
        check_rc, checked = invoke("--check")
        checks = {
            "first run": first_rc == 0 and first.get("drift") is True,
            "idempotent": check_rc == 0 and checked.get("drift") is False,
            "memory": _read(root / "AGENTS.md") == "# 正文\n" and _is_shell(_read(root / "CLAUDE.md")),
            "claude command": bool(command) and (root / CLAUDE_COMMANDS / f"{command}.md").is_file(),
            "codex command": bool(command) and (root / CODEX_COMMAND_SKILLS / command / "SKILL.md").is_file(),
            "dsh command": bool(command) and (root / DSH_COMMANDS / f"{command}.md").is_file(),
            "shared skill": bool(skill) and (root / SHARED_SKILLS / skill / "SKILL.md").is_file(),
            "no router": not (root / SHARED_SKILLS / OBSOLETE_ROUTER).exists(),
            "claude plugin": plugin is None or (root / CLAUDE_PLUGINS / plugin.name).is_dir(),
            "shared plugin skill": (plugin is None or not plugin_skill
                                    or (root / SHARED_SKILLS / plugin.name / "skills"
                                        / plugin_skill / "SKILL.md").is_file()),
            "no codex plugin duplicate": plugin is None or not (root / CODEX_PLUGIN_SKILLS / plugin.name).exists(),
            "hook": "codex_hooks = true" in _read(root / ".codex/config.toml"),
        }
        if command:
            (runtime / "commands" / f"{command}.md").unlink()
            checks["stale command detected"] = invoke("--check")[1].get("drift") is True
        bad = [name for name, passed in checks.items() if not passed]
        print(json.dumps({"self_check": "fail" if bad else "pass", "failed": bad}, ensure_ascii=False))
        return 1 if bad else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=".")
    ap.add_argument("--agents", default="", help="逗号分隔：claude,codex,dsh；缺省按项目根目录检测")
    ap.add_argument("--mode", choices=("link", "copy"), default="copy")
    ap.add_argument("--check", action="store_true", help="只检查不写，有漂移 exit 1")
    ap.add_argument("--human", action="store_true")
    ap.add_argument("--self-check", action="store_true")
    a = ap.parse_args(argv)
    if a.self_check:
        return _self_check()
    root = Path(a.root).resolve()
    required = ("commands", "skills", "plugins", "scripts")
    missing = [name for name in required if not (RUNTIME_ROOT / name).is_dir()]
    if missing:
        print(json.dumps({"error": f"AIDP 运行包不完整：{','.join(missing)}"}, ensure_ascii=False))
        return 2
    if a.agents:
        agents = [x.strip() for x in a.agents.split(",") if x.strip()]
        unknown = [x for x in agents if x not in KNOWN_AGENTS]
        if unknown:
            print(json.dumps({"error": f"未知 Agent：{unknown}，可选 {list(KNOWN_AGENTS)}"}, ensure_ascii=False))
            return 2
    else:
        agents = detect_agents(root)
    try:
        result = run(root, agents, a.mode, apply=not a.check)
    except SystemExit as exc:
        print(json.dumps({"error": str(exc)}, ensure_ascii=False))
        return 2
    print(json.dumps(result, ensure_ascii=False))
    if a.human:
        for act in result["actions"]:
            print(f"  {act['op']:6} {act['path']}", file=sys.stderr)
    return 1 if (a.check and result["drift"]) else 0


if __name__ == "__main__":
    sys.exit(main())
